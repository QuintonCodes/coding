arr = [1, 2, 3, 4, 5, 6]

print(arr[1:4])

# The start (1) slices the left from index 1 but not including the value of index 1
# The end (4) slices the right from index 4, including the value of index 4

print(arr[-5:-2])

# The start (-4) slices from the left from index -4, including the value of the index
# The end (-1) slices from the right from index -1, excluding the value of the index

print(arr[:3])